void touch_ctrl(void)
{
	if(nrf_gpio_pin_read(TOUCH_BUTTON_03) == 1)
	{
		while(nrf_gpio_pin_read(TOUCH_BUTTON_03) == 1);
		buzzer_ctrl(true, 20) ;
		led_toggle(LED_17);
		led_toggle(LED_18);
		led_toggle(LED_19);
		led_toggle(LED_20);
	}

}
