void touch_pad_init(void)
{
	// 触摸按键 gpio 引脚为 p0.03， 触摸后输出H, 无触摸时为L 
	nrf_gpio_cfg_input(TOUCH_BUTTON_03,NRF_GPIO_PIN_PULLUP);  //  配置引脚16 为下拉输入
}
