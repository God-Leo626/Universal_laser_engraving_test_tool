bool  decrypt_data(uint8_t * data_string, unsigned char string_len, uint8_t * target_buf, int buf_size)
{
    uint8_t   encrypt_idx = 0 ;          // 用于保存原始数据中的码表起始位置
    memset(target_buf,'\0',buf_size);
    if(buf_size < 22 )
    {
        return false ;
    }
    
    if(check_sum(data_string,string_len) == true)   // 待解密的数据完整有效时
    {
        encrypt_idx = data_string[9];    //  从原始数据中取出码表开始位置
        // encrypt_indx为随机数(小于等于255-21)
        if(encrypt_idx > (255 - 21))    // encrypt_idx + 20 不能越界，encrypt_key 共 255 个元素
        {
            return false;               // 拒绝处理异常索引
        }
//        print("encrypt_idx = %02X\r\n",encrypt_idx);
        for(unsigned char i = 0 ; i < 21 ; i++)   //  对payload 为 21的数据根据码表异或解密
        {
            target_buf[i] = data_string[i + 10] ^ encrypt_key[encrypt_idx + i ] ;   // 异或解密数据并保存到data_buf
        }
        target_buf[21] = '\0';             //  最后加上结束字符
        return true ;
    }
    else
    {
        return false ;
    }
}

