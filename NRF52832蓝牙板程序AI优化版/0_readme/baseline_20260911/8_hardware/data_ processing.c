void feature_set(const char *hex_str)
{
    char *end ;   // 保存 strtol 转换的结果
    feature_raw_len = 0;    //  函数中转换好的十六进制的个数 （先清0 ）
    size_t len = strlen(hex_str);   // 获取将要转换的十六进制的字符串 长度
    if (len % 2 != 0)
    {
        return;                    // 奇数个字符 → 非法输入，丢弃
    }        
    for (size_t i = 0; i < len; i += 2) // 每次取 2 个字符转 1 字节
    {
        char buf[3] = {hex_str[i], hex_str[i+1], '\0'};
        feature_raw[feature_raw_len++] = (uint8_t)strtol(buf, &end, 16); // 转成字节并存入数组，长度 +1  （strtol 将 02，转换成0x02）
        if(*end == '\0')  // 转换成功
        {
            feature_global_flag = true;
        }
    }
}

