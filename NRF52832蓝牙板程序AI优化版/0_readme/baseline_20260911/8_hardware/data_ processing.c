static bool check_sum(uint8_t * data_string,unsigned char string_len)
{
    uint8_t sum = 0 ;        // 保存累加和
    if( string_len < 31)  // 入参的字符长度判断， 小于31的，直接返回
    {
        return false ;
    }
    for(char i = 0 ; i <= 21 ; i++)  // 0--21 一共22个数字参与校验和计算
    {
        sum += data_string[i+9] ;  // 从data 的第9位开始，第9位是 encrypt idx
    }
    if(sum == data_string[8] )  //  data  的第8位是广播的校验和
    {
//        print("check_sum = %02X\r\n",sum);
        return true ;
    }
    else
    {
        return false ;
    }
    
}
